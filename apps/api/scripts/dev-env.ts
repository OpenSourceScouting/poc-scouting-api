/** Helpers for the local-only .dev.vars file and the local signing key. Never used in deployed environments. */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

export const DEV_VARS = resolve(import.meta.dirname, '../.dev.vars');
export const DEV_SIGNING_KEY = resolve(import.meta.dirname, '../.dev-oauth-private.jwk.json');

export function readDevVars(): Record<string, string> {
  if (!existsSync(DEV_VARS)) return {};
  const vars: Record<string, string> = {};
  for (const line of readFileSync(DEV_VARS, 'utf8').split('\n')) {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (match?.[1]) vars[match[1]] = (match[2] ?? '').replace(/^'(.*)'$/, '$1');
  }
  return vars;
}

export function writeDevVars(vars: Record<string, string>): void {
  const body = Object.entries(vars)
    .map(([k, v]) => `${k}='${v}'`)
    .join('\n');
  writeFileSync(DEV_VARS, `# Local development only. Generated by npm run dev:setup. Never commit.\n${body}\n`);
}
