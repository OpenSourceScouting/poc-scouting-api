/**
 * Writes seed/seed.sql from the fictional sample adults in scripts/sample-adults.ts, hashed with the local
 * NAME_HASH_KEY, and writes the catalog docs/sample-data.md from the same list. The reserved test identities
 * must also be loaded by the real sync in every environment (see docs/reserved-test-identities.md).
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { hashLastName } from '../src/platform/adult-check';
import { readDevVars } from './dev-env';
import { AS_OF, ENDED, EARLIER, LATER, sampleAdults, type SampleAdult } from './sample-adults';

const key = readDevVars().NAME_HASH_KEY;
if (!key) throw new Error('NAME_HASH_KEY missing; run npm run dev:setup first');

const adults = sampleAdults();

const q = (v: string) => `'${v.replaceAll("'", "''")}'`;
const lines = [
  '-- GENERATED by scripts/generate-seed.ts with the local NAME_HASH_KEY. Fictional data only. Do not commit.',
  'DELETE FROM position_assignments;',
  'DELETE FROM membership_status;',
  'DELETE FROM ypt_status;',
  `INSERT OR REPLACE INTO sync_state (id, as_of) VALUES (1, ${q(AS_OF)});`,
];
let positionRows = 0;
for (const a of adults) {
  lines.push(`-- ${a.id}: ${a.useCase}`);
  const hash = q(await hashLastName(key, a.lastName));
  if (a.ypt) lines.push(`INSERT INTO ypt_status VALUES (${q(a.id)}, ${hash}, ${q(a.ypt)});`);
  if (a.membership) lines.push(`INSERT INTO membership_status VALUES (${q(a.id)}, ${hash}, ${q(a.membership)});`);
  for (const [org, code, end] of a.positions ?? []) {
    positionRows++;
    lines.push(
      `INSERT INTO position_assignments (member_id, organization_id, position_code, last_name_hash, expires_at) VALUES (${q(a.id)}, ${q(org)}, ${q(code)}, ${hash}, ${q(end)});`,
    );
  }
}
const sqlPath = resolve(import.meta.dirname, '../seed/seed.sql');
writeFileSync(sqlPath, `${lines.join('\n')}\n`);

// The catalog uses words instead of timestamps, so it does not change each time you seed.
const describe = (end: string | undefined): string => {
  if (end === undefined) return 'no record';
  if (end === LATER || end === EARLIER) return 'current';
  if (end === ENDED) return 'ended';
  return Date.parse(end) > Date.now() ? 'current, ends soon' : 'ended recently';
};
const describePositions = (a: SampleAdult): string =>
  (a.positions ?? []).map(([org, code, end]) => `${code} in \`${org}\` (${describe(end)})`).join('; ') || 'none';
const cell = (s: string) => s.replaceAll('|', '\\|');

const doc: string[] = [
  '# Sample data',
  '',
  '<!-- GENERATED by apps/api/scripts/generate-seed.ts from apps/api/scripts/sample-adults.ts. Do not edit. -->',
  '',
  'This page lists the fictional adults in the local seed data. Use it to try a check, to test a tool, or to',
  'find a case to reproduce. All people and organizations are fictional. The position codes are placeholders.',
  '',
  'To load the data on your computer, run `npm run db:reset -w @scouting/api`. To check each case against the',
  'running API, run `npm run db:verify-seed -w @scouting/api`.',
  '',
  'Some cases use times relative to the moment that you seed. "Ends soon" means 1 hour or 30 days after you seed.',
  '"Ended recently" means 1 hour before you seed.',
];
for (const group of [...new Set(adults.map((a) => a.group))]) {
  doc.push('', `## ${group}`, '', 'The table gives each adult in this group:', '');
  doc.push('| Member ID | Last name | Also matches | YPT | Membership | Positions | Use case |');
  doc.push('| --- | --- | --- | --- | --- | --- | --- |');
  for (const a of adults.filter((x) => x.group === group)) {
    const also = (a.sendAs ?? []).map((v) => `\`${v}\``).join(', ') || 'none';
    doc.push(
      `| \`${a.id}\` | \`${cell(a.lastName)}\` | ${cell(also)} | ${describe(a.ypt)} | ${describe(a.membership)} | ${cell(describePositions(a))} | ${cell(a.useCase)} |`,
    );
  }
}
doc.push(
  '',
  '## Cases without a record',
  '',
  'Some cases have no row in the seed data, because the platform never stores them:',
  '',
  '- **A youth member.** Use any member ID that the tables do not contain, for example `500000001`. Each check',
  '  answers `notCurrent`.',
  '- **An adult who opted out.** The sync leaves this adult out, so each check answers `notCurrent`.',
  '- **A wrong last name.** Send any member ID from the tables with a different last name. Each check answers',
  '  `notCurrent`.',
  '',
);
const docPath = resolve(import.meta.dirname, '../../../docs/sample-data.md');
writeFileSync(docPath, doc.join('\n'));

console.log(`Wrote ${sqlPath} (${adults.length} adults, ${positionRows} position terms) and ${docPath}`);
